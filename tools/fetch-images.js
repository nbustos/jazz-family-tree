#!/usr/bin/env node
// Resolves a free-license portrait for every artist and writes data/images.js.
// Source: Wikipedia PageImages (free images only), falling back to the Wikidata P18 image.
// Usage: node tools/fetch-images.js
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const UA = "JazzFamilyTree/1.0 (https://github.com/nbustos/jazz-family-tree; static site image resolver)";
const THUMB = 250, LARGE = 500;

const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, "data/core.js"), "utf8"), ctx);
for (const f of fs.readdirSync(path.join(root, "data/artists")).filter((f) => f.endsWith(".js")).sort())
  vm.runInContext(fs.readFileSync(path.join(root, "data/artists", f), "utf8"), ctx);
const artists = ctx.JAZZ.artists;

const get = async (url) => {
  for (let attempt = 0; attempt < 4; attempt++) {
    const r = await fetch(url, { headers: { "User-Agent": UA, "Api-User-Agent": UA } });
    if (r.ok) return r.json();
    await new Promise((res) => setTimeout(res, 1500 * (attempt + 1)));
  }
  throw new Error("failed: " + url);
};
const thumbAt = (url, w) => url.replace(/\/(\d+)px-([^/]+)$/, `/${w}px-$2`);

(async () => {
  const out = {};
  const titleOf = new Map(); // final title → [ids]
  const batches = [];
  for (let i = 0; i < artists.length; i += 40) batches.push(artists.slice(i, i + 40));
  const missing = [];
  for (const batch of batches) {
    const titles = batch.map((a) => a.wiki.replace(/_/g, " "));
    const url = "https://en.wikipedia.org/w/api.php?action=query&format=json&formatversion=2&redirects=1"
      + `&prop=pageimages|pageprops&piprop=thumbnail|name&pithumbsize=${THUMB}&ppprop=wikibase_item&titles=`
      + encodeURIComponent(titles.join("|"));
    const data = await get(url);
    const map = new Map(titles.map((t) => [t, t]));
    for (const n of data.query.normalized || []) for (const [k, v] of map) if (v === n.from) map.set(k, n.to);
    for (const r of data.query.redirects || []) for (const [k, v] of map) if (v === r.from) map.set(k, r.to);
    const pages = new Map(data.query.pages.map((p) => [p.title, p]));
    batch.forEach((a, i) => {
      const p = pages.get(map.get(titles[i]));
      if (!p || p.missing) { missing.push({ a, qid: null, reason: "no page" }); return; }
      if (p.thumbnail) {
        const src = p.thumbnail.source;
        out[a.id] = {
          src, large: /\/\d+px-/.test(src) ? thumbAt(src, LARGE) : src,
          w: p.thumbnail.width, h: p.thumbnail.height, file: p.pageimage,
        };
      } else missing.push({ a, qid: p.pageprops && p.pageprops.wikibase_item, reason: "no free page image" });
    });
    titleOf.set(batch[0].id, true);
  }

  // Fallback: Wikidata P18.
  const withQ = missing.filter((m) => m.qid);
  for (let i = 0; i < withQ.length; i += 40) {
    const chunk = withQ.slice(i, i + 40);
    const data = await get("https://www.wikidata.org/w/api.php?action=wbgetentities&format=json&props=claims&ids=" + chunk.map((m) => m.qid).join("|"));
    for (const m of chunk) {
      const claim = data.entities[m.qid]?.claims?.P18?.[0]?.mainsnak?.datavalue?.value;
      if (!claim) continue;
      const file = claim.replace(/ /g, "_");
      const base = "https://commons.wikimedia.org/wiki/Special:FilePath/" + encodeURIComponent(file);
      out[m.a.id] = { src: `${base}?width=${THUMB}`, large: `${base}?width=${LARGE}`, file };
      m.resolved = true;
    }
  }

  const sorted = Object.fromEntries(Object.keys(out).sort().map((k) => [k, out[k]]));
  fs.writeFileSync(path.join(root, "data/images.js"),
    "// Generated by tools/fetch-images.js — free-license portraits from Wikimedia Commons.\n"
    + "window.JAZZ.images = " + JSON.stringify(sorted, null, 1) + ";\n");
  const unresolved = missing.filter((m) => !m.resolved);
  console.log(`${Object.keys(out).length}/${artists.length} artists have images.`);
  if (unresolved.length) console.log("No image:", unresolved.map((m) => `${m.a.id} (${m.reason})`).join(", "));
})();
