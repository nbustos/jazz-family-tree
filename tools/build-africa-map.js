#!/usr/bin/env node
// Builds data/roots/africa-map.js — SVG paths for Africa's countries (plus faint neighbouring land for
// context) from Natural Earth admin-0 countries (public domain, naturalearthdata.com).
// Usage: node tools/build-africa-map.js path/to/ne_50m_admin_0_countries.geojson
const fs = require("fs");
const path = require("path");

const src = process.argv[2];
if (!src) { console.error("usage: node tools/build-africa-map.js ne_50m_admin_0_countries.geojson"); process.exit(1); }
const geo = JSON.parse(fs.readFileSync(src, "utf8"));

const LON0 = -26, LON1 = 64, LAT0 = 40, LAT1 = -38;   // view window (degrees)
const S = 10;                                           // px per degree
const K = Math.cos((8 * Math.PI) / 180);                // mild equal-area-ish horizontal squeeze
const W = Math.round((LON1 - LON0) * S * K), H = Math.round((LAT0 - LAT1) * S);
const X = (lon) => (lon - LON0) * S * K;
const Y = (lat) => (LAT0 - lat) * S;
const FIX = { SAH: "ESH", SDS: "SSD", SOL: "SOM" };     // Natural Earth codes → ISO 3166 alpha-3

function ringPath(ring, minStep) {
  const pts = [];
  let last = null;
  for (const [lon, lat] of ring) {
    const p = [X(lon), Y(lat)];
    if (last && Math.hypot(p[0] - last[0], p[1] - last[1]) < minStep) continue;
    pts.push(p); last = p;
  }
  if (pts.length < 3) return "";
  return "M" + pts.map((p) => `${p[0].toFixed(1)},${p[1].toFixed(1)}`).join("L") + "Z";
}
function featurePath(f, minStep) {
  const g = f.geometry;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : [];
  return polys.map((poly) => poly.map((r) => ringPath(r, minStep)).join("")).join("");
}
const inWindow = (f) => {
  const g = f.geometry;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  return polys.some((poly) => poly[0].some(([lon, lat]) => lon > LON0 && lon < LON1 && lat < LAT0 && lat > LAT1));
};

const countries = {}, names = {};
let context = "";
for (const f of geo.features) {
  const p = f.properties;
  if (p.CONTINENT === "Africa") {
    const code = FIX[p.ADM0_A3] || p.ADM0_A3;
    countries[code] = (countries[code] || "") + featurePath(f, 1.2);
    names[code] = names[code] || p.NAME;
  } else if (inWindow(f)) {
    context += featurePath(f, 2);
  }
}

const out = `// Generated by tools/build-africa-map.js from Natural Earth 1:50m admin-0 countries (public domain).
window.AFRICA_MAP = ${JSON.stringify({ width: W, height: H, lon0: LON0, lat0: LAT0, scale: S, squeeze: K, countries, names, context })};
`;
fs.writeFileSync(path.join(__dirname, "..", "data/roots/africa-map.js"), out);
console.log(`${Object.keys(countries).length} countries, ${(out.length / 1024).toFixed(0)} KB, ${W}×${H}`);
