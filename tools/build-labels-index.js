#!/usr/bin/env node
// Builds data/labels/by-artist.js — a small index from artist id to the labels and venues on the
// Labels & Locals page that name them, so the tree's artist panel can link there without loading it all.
// Usage: node tools/build-labels-index.js
const fs = require("fs");
const path = require("path");
global.window = global;
const root = path.join(__dirname, "..");
require(path.join(root, "data/labels/core.js"));
for (const f of fs.readdirSync(path.join(root, "data/labels")).sort()) {
  if (["core.js", "world-map.js", "by-artist.js"].includes(f) || !f.endsWith(".js")) continue;
  require(path.join(root, "data/labels", f));
}
const L = global.LABELS;
const idx = {};
const add = (aid, key, entry) => {
  if (!aid) return;
  const e = (idx[aid] = idx[aid] || { l: [], c: [] });
  if (!e[key].some((x) => x[0] === entry[0])) e[key].push(entry);
};
const short = (l) => l.short || l.name.replace(/ (Records|Recordings|Record Company|Talking Machine Company|Phonograph Corporation|Phonograph Company|Music)$/i, "").replace(/^Disques /, "");
for (const l of L.labels) {
  const ids = new Set([...(l.artists || []), ...(l.records || []).flatMap((r) => r.artistIds || []), ...(l.people || []).map((p) => p.artistId)]);
  for (const a of ids) add(a, "l", [l.id, short(l)]);
}
for (const c of L.clubs) {
  const ids = new Set([...(c.regulars || []), ...(c.live || []).flatMap((r) => r.artistIds || []), ...(c.people || []).map((p) => p.artistId)]);
  for (const a of ids) add(a, "c", [c.id, c.name]);
}
const out = `// Generated by tools/build-labels-index.js — artist id → labels (l) and venues (c) on labels.html.
window.JAZZ_SCENES = ${JSON.stringify(idx)};
`;
fs.writeFileSync(path.join(root, "data/labels/by-artist.js"), out);
console.log(`${Object.keys(idx).length} artists indexed, ${(out.length / 1024).toFixed(1)} KB`);
