#!/usr/bin/env node
// Builds data/labels/world-map.js — a world land outline (country borders included) in the Equal Earth
// projection, from Natural Earth admin-0 countries (public domain, naturalearthdata.com).
// Usage: node tools/build-world-map.js path/to/ne_50m_admin_0_countries.geojson
const fs = require("fs");
const path = require("path");

const src = process.argv[2];
if (!src) { console.error("usage: node tools/build-world-map.js ne_50m_admin_0_countries.geojson"); process.exit(1); }
const geo = JSON.parse(fs.readFileSync(src, "utf8"));

// Equal Earth (Šavrič, Patterson & Jenny 2018). The page uses the same function to place cities.
const A1 = 1.340264, A2 = -0.081106, A3 = 0.000893, A4 = 0.003796, M = Math.sqrt(3) / 2;
function equalEarth(lon, lat) {
  const l = (lon * Math.PI) / 180, t = Math.asin(M * Math.sin((lat * Math.PI) / 180));
  const t2 = t * t, t6 = t2 * t2 * t2;
  return [(l * Math.cos(t)) / (M * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2))), t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2))];
}
const S = 165;                                  // px per projected unit
const [xMin] = equalEarth(-180, 0), [xMax] = equalEarth(180, 0);
const yTop = equalEarth(0, 75)[1], yBot = equalEarth(0, -50)[1];
const W = Math.round((xMax - xMin) * S), H = Math.round((yTop - yBot) * S);
const P = (lon, lat) => { const [x, y] = equalEarth(lon, lat); return [(x - xMin) * S, (yTop - y) * S]; };

function ringPath(ring, minStep) {
  const pts = [];
  let last = null;
  for (const [lon, lat] of ring) {
    const p = P(lon, Math.max(-50, Math.min(75, lat)));
    if (last && Math.hypot(p[0] - last[0], p[1] - last[1]) < minStep) continue;
    pts.push(p); last = p;
  }
  if (pts.length < 3) return "";
  return "M" + pts.map((p) => `${p[0].toFixed(1)},${p[1].toFixed(1)}`).join("L") + "Z";
}

let land = "";
for (const f of geo.features) {
  if (f.properties.CONTINENT === "Antarctica") continue;
  const g = f.geometry;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : [];
  for (const poly of polys) {
    // Drop tiny islands that would only be specks at this scale.
    const xs = poly[0].map(([lon, lat]) => P(lon, lat));
    const w = Math.max(...xs.map((p) => p[0])) - Math.min(...xs.map((p) => p[0]));
    const h = Math.max(...xs.map((p) => p[1])) - Math.min(...xs.map((p) => p[1]));
    if (w < 1.2 && h < 1.2) continue;
    land += ringPath(poly[0], 1.0);
  }
}

const out = `// Generated by tools/build-world-map.js from Natural Earth 1:50m admin-0 countries (public domain). Equal Earth projection.
window.WORLD_MAP = ${JSON.stringify({ width: W, height: H, scale: S, xMin, yTop, land })};
`;
fs.writeFileSync(path.join(__dirname, "..", "data/labels/world-map.js"), out);
console.log(`${(out.length / 1024).toFixed(0)} KB, ${W}×${H}`);
