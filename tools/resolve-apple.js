#!/usr/bin/env node
// Looks up each track in data/playlists.js with Apple's public iTunes Search API and writes
// data/playlists-apple.js: "artist|title" → { url, artist, album } for tracks with a confident match
// (title and a word of the artist name must both match; the original album, a leader-first credit and a period
// compilation score higher, live versions, remakes and fake-stereo reissues lower). Unmatched tracks fall back to an Apple Music
// search link on the page. Already-resolved tracks are kept unless --all is passed.
// Usage: node tools/resolve-apple.js [--all]
const fs = require("fs");
const path = require("path");
global.window = global;
const root = path.join(__dirname, "..");
require(path.join(root, "data/playlists.js"));
const out = path.join(root, "data/playlists-apple.js");
let known = {};
if (fs.existsSync(out) && !process.argv.includes("--all")) { require(out); known = global.PLAYLISTS_APPLE || {}; }

const norm = (s) => String(s).normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase()
  .replace(/&/g, " and ").replace(/\(.*?\)|\[.*?\]/g, " ").replace(/[^a-z0-9 ]+/g, " ").replace(/\s+/g, " ").trim();
const STOP = new Set(["the", "and", "his", "her", "orchestra", "band", "trio", "quartet", "quintet", "sextet", "feat", "with", "of", "de", "du", "club", "s"]);
const artistWords = (a) => norm(a.split(/ feat\.? /i)[0]).split(" ").filter((w) => w.length > 2 && !STOP.has(w));
const COMPILATION = /best of|greatest|essential|collection|hits|anthology|complete|100 |ultimate|gold|playlist|jazz classics|various/i;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function look(t) {
  const term = `${t.artist.split(/ feat\.? /i)[0]} ${t.title}`.replace(/[“”"']/g, "");
  const url = `https://itunes.apple.com/search?${new URLSearchParams({ term, media: "music", entity: "song", limit: "50", country: "us" })}`;
  for (let attempt = 0; attempt < 3; attempt++) {
    const res = await fetch(url);
    if (res.status === 403 || res.status === 429) { await sleep(20000); continue; }
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const { results } = await res.json();
    const lead = t.artist.split(/ feat\.? /i)[0], want = norm(t.title), words = artistWords(t.artist);
    const scored = (results || []).map((r) => {
      const title = norm(r.trackName), artist = norm(r.artistName);
      if (!(title === want || title.startsWith(want + " ") || (want.length > 8 && title.includes(want)))) return null;
      if (!words.some((w) => artist.includes(w))) return null;
      const coll = r.collectionName || "", ca = norm(coll);
      let s = title === want ? 10 : 5;
      if (words.every((w) => artist.includes(w))) s += 3;
      if (norm(lead) === artist) s += 5;
      else if (artist.startsWith(words[0])) s += 4;
      if (t.album && (ca.startsWith(norm(t.album)) || norm(t.album).startsWith(ca))) s += 12;
      if (!COMPILATION.test(coll)) s += 3;
      if (t.year && t.year < 1960 && new RegExp(`\\b${t.year}\\b|\\b${String(t.year).slice(0, 3)}\\d\\b`).test(coll)) s += 3;
      if (/\blive\b/i.test(coll + r.trackName) && !/live/i.test((t.album || "") + (t.when || ""))) s -= 6;
      if (/super stereo|re-?record(ed|ing)|soundtrack|8d|slowed|sped up|lofi|lo-fi|lullaby|piano version|instrumental version/i.test(coll + r.trackName)) s -= 15;
      if (/alternate|alt\. take|single edit|45 rpm|radio (version|edit)|monophonic|mono mix|riot version|rehearsal|false start|breakdown|incomplete/i.test(r.trackName + coll)) s -= 12;
      if (/\btake \d/i.test(r.trackName)) s -= 2;
      if (/karaoke|tribute|cover|made famous|in the style/i.test(coll + r.artistName)) s -= 20;
      return { s, r };
    }).filter(Boolean).sort((a, b) => b.s - a.s);
    if (!scored.length || scored[0].s < 0) return null;
    const r = scored[0].r;
    return { url: r.trackViewUrl.replace(/&uo=\d+/, ""), artist: r.artistName, album: r.collectionName };
  }
  throw new Error("rate-limited");
}

(async () => {
  const res = { ...known };
  let hit = 0, miss = 0;
  for (const p of global.PLAYLISTS) for (const t of p.tracks) {
    const key = `${t.artist}|${t.title}`;
    if (t.apple === false) { delete res[key]; miss++; continue; } // hand-checked: Apple only has another version
    if (res[key]) { hit++; continue; }
    try {
      const m = await look(t);
      if (m) { res[key] = m; hit++; console.log(`✓ ${t.title} — ${m.artist} · ${m.album}`); }
      else { miss++; console.log(`· no match: ${t.title} — ${t.artist}`); }
    } catch (e) { miss++; console.log(`✗ ${t.title}: ${e.message}`); }
    await sleep(3200); // the API allows roughly 20 requests a minute
  }
  fs.writeFileSync(out, `// Generated by tools/resolve-apple.js — Apple Music track links for data/playlists.js ("artist|title" → match).\nwindow.PLAYLISTS_APPLE = ${JSON.stringify(res, null, 1)};\n`);
  console.log(`\n${hit} matched, ${miss} unmatched (search link fallback)`);
})();
